import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const exec=promisify(execFile),root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const home=path.join(root,'desktop/audio-helper'),lock=JSON.parse(await fs.readFile(path.join(home,'rubberband.lock.json'),'utf8'));
if(process.platform!=='darwin'||process.arch!=='arm64')throw new Error('Audio helper build currently supports macOS arm64 only');
const archive=path.join(home,lock.sourceArchive),bytes=await fs.readFile(archive);
if(bytes.length!==lock.bytes||createHash('sha256').update(bytes).digest('hex')!==lock.sha256)throw new Error('Pinned Rubber Band source archive identity mismatch');
const cache=path.join(root,'.cache/audio-helper');await fs.mkdir(cache,{recursive:true});
const env={...process.env,LC_ALL:'C',LANG:'C'};
await exec('/usr/bin/tar',['-xzf',archive,'-C',cache],{env});
const source=path.join(cache,`rubberband-${lock.version}`),binary=path.join(home,'bin/darwin-arm64/weijian-audio-helper');
await fs.mkdir(path.dirname(binary),{recursive:true});
const args=['--sdk','macosx','clang++','-std=c++17','-O3','-DNDEBUG','-arch','arm64','-mmacosx-version-min=13.0','-I',source,path.join(home,'main.cpp'),path.join(source,'single/RubberBandSingle.cpp'),'-framework','Accelerate','-o',binary];
await exec('/usr/bin/xcrun',args,{env,maxBuffer:2*1024*1024});await fs.chmod(binary,0o755);
const result=await exec(binary,['--version'],{env});
const metadata={version:lock.version,sourceSha256:lock.sha256,binarySha256:createHash('sha256').update(await fs.readFile(binary)).digest('hex'),binaryBytes:(await fs.stat(binary)).size,platform:process.platform,arch:process.arch,minimumMacOS:'13.0',compilerArgs:args,versionOutput:result.stdout.trim(),dynamicDependencies:(await exec('/usr/bin/otool',['-L',binary],{env})).stdout};
await fs.writeFile(path.join(home,'build-receipt.json'),JSON.stringify(metadata,null,2)+'\n');console.log(JSON.stringify(metadata,null,2));
